# Write all 3 JSON dictionary files
$jsonOpts = [System.Text.Json.JsonSerializerOptions]@{WriteIndented = $true; Encoder = [System.Text.Encodings.Web.JavaScriptEncoder]::UnsafeRelaxedJsonEscaping}

function Write-Dict($hash, $path) {
    $json = [System.Text.Json.JsonSerializer]::Serialize($hash, $jsonOpts)
    [System.IO.File]::WriteAllText($path, $json, [System.Text.UTF8Encoding]::new($false))
    Write-Host "Written: $path ($($hash.Count) entries)"
}

Write-Dict -hash $ptPT -path "$scriptDir/dict-pt-PT.json"
Write-Dict -hash $ptBR -path "$scriptDir/dict-pt-BR.json"
Write-Dict -hash $esES -path "$scriptDir/dict-es-ES.json"

Write-Host "Done! pt-PT: $($ptPT.Count), pt-BR: $($ptBR.Count), es-ES: $($esES.Count)"
